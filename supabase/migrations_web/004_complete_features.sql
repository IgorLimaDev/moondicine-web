-- Complete features migration for Moondicine Web
-- Run this in Supabase SQL Editor

-- Create question_flags table
CREATE TABLE IF NOT EXISTS public.question_flags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES public.questions(id) ON DELETE CASCADE,
    flagged_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(user_id, question_id)
);

CREATE INDEX IF NOT EXISTS idx_question_flags_user_id ON public.question_flags(user_id);
CREATE INDEX IF NOT EXISTS idx_question_flags_question_id ON public.question_flags(question_id);

-- Create question_notes table
CREATE TABLE IF NOT EXISTS public.question_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES public.questions(id) ON DELETE CASCADE,
    note_text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_question_notes_user_id ON public.question_notes(user_id);
CREATE INDEX IF NOT EXISTS idx_question_notes_question_id ON public.question_notes(question_id);

-- Create user_stats table per user
CREATE TABLE IF NOT EXISTS public.user_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    specialty TEXT NOT NULL,
    total_answered INTEGER NOT NULL DEFAULT 0,
    total_correct INTEGER NOT NULL DEFAULT 0,
    average_time_seconds REAL NOT NULL DEFAULT 0,
    last_studied_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    weakest_sub_topics JSONB NOT NULL DEFAULT '[]'::jsonb,
    UNIQUE(user_id, specialty)
);

CREATE INDEX IF NOT EXISTS idx_user_stats_user_id ON public.user_stats(user_id);

-- Update user_profiles to include streak and more fields if not exist
ALTER TABLE public.user_profiles ADD COLUMN IF NOT EXISTS total_questions_answered INTEGER DEFAULT 0;
ALTER TABLE public.user_profiles ADD COLUMN IF NOT EXISTS current_streak_days INTEGER DEFAULT 0;
ALTER TABLE public.user_profiles ADD COLUMN IF NOT EXISTS last_study_date TIMESTAMPTZ;
ALTER TABLE public.user_profiles ADD COLUMN IF NOT EXISTS total_study_time_minutes INTEGER DEFAULT 0;
ALTER TABLE public.user_profiles ADD COLUMN IF NOT EXISTS target_specialty TEXT DEFAULT '';

-- Enable RLS
ALTER TABLE public.question_flags ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.question_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_stats ENABLE ROW LEVEL SECURITY;

-- RLS Policies for question_flags
DROP POLICY IF EXISTS "Users can manage own flags" ON public.question_flags;
CREATE POLICY "Users can manage own flags"
    ON public.question_flags FOR ALL
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- RLS Policies for question_notes
DROP POLICY IF EXISTS "Users can manage own notes" ON public.question_notes;
CREATE POLICY "Users can manage own notes"
    ON public.question_notes FOR ALL
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- RLS Policies for user_stats
DROP POLICY IF EXISTS "Users can manage own stats" ON public.user_stats;
CREATE POLICY "Users can manage own stats"
    ON public.user_stats FOR ALL
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- Update question_notes trigger
CREATE OR REPLACE FUNCTION public.update_question_notes_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS update_question_notes_updated_at ON public.question_notes;
CREATE TRIGGER update_question_notes_updated_at
    BEFORE UPDATE ON public.question_notes
    FOR EACH ROW EXECUTE FUNCTION public.update_question_notes_updated_at();
